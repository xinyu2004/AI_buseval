def set_lang(lang: str) -> None:
    global _LANG
    if lang in STRINGS:
        _LANG = lang


def lang() -> str:
    return _LANG


def t(key: str) -> str:
    return STRINGS[_LANG].get(key, STRINGS["zh"].get(key, key))


