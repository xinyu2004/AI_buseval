_PATTERNS = [
    (re.compile(r"^aggressive FLASH util_pct=(.+)$"), "assume_flash"),
    (re.compile(r"^aggressive CAN load_pct=(.+)$"), "assume_can"),
    (re.compile(r"^aggressive ETH util_pct=(.+)$"), "assume_eth"),
    (re.compile(r"^stream (.+) MB/s exceeds (.+)G link (.+) MB/s$"), "assume_eth_link"),
    (re.compile(r"^aggressive USB util_pct=(.+)$"), "assume_usb"),
    (re.compile(r"^carried (.+) MB/s exceeds (\d+)-lane capacity (.+) MB/s$"), "assume_carried"),
    (re.compile(r"^aggregate (.+) MB/s \((\d+) streams\) exceeds (\d+)-lane capacity (.+) MB/s$"), "assume_aggregate_lane"),
    (re.compile(r"^inference_fps (.+) < source '(.+)' fps (.+) \(async; not capped\)$"), "assume_npu_fps"),
    (re.compile(r"^tops_used (.+) > (.+) of peak (.+)$"), "assume_tops"),
    (re.compile(r"^non-typical stage '(.+)' factor > (.+)$"), "assume_stage"),
]


def localize(message: str) -> str:
    key = _FIXED.get(message)
    if key:
        return t(key)
    for pattern, key in _PATTERNS:
        match = pattern.match(message)
        if match:
            return t(key).format(*match.groups())
    return message


def level_text(code: str) -> str:
    key = f"lv_{code}"
    return t(key) if key in STRINGS[_LANG] else code


def verdict_text(code: str) -> str:
    key = f"v_{code}"
    return t(key) if key in STRINGS[_LANG] else code
